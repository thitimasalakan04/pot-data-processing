def extract_province(text):
    if not isinstance(text, str):
        return None
        
    for keyword, correct_province in mapping_dict.items():
        if keyword in text:
            return correct_province  
            
    for province in provinces:
        if province in text:
            return province
            
    return None

def extract_line_contact(text):
    if not isinstance(text, str):
        return None
    
    # หา Line OA ที่ขึ้นต้นด้วย @
    at_match = re.search(r'@[A-Za-z0-9_.-]+', text)
    if at_match:
        return at_match.group(0)
        
    # หาคำว่า Line, ID, ไอดี ตามด้วยชื่อไอดี
    matches = re.finditer(r'(?i)(?:line\s*id|id|line|ไอดี|แอดไลน์)\s*[:=]?\s*([A-Za-z0-9_.-]+)', text)
    
    for match in matches:
        extracted_id = match.group(1)
        
        # กรองคำผิดพลาด
        blacklist = ['puff', 'pod','httpps','http','-http','.com','5000puffs','man','mang','official','https','.me','me','year','---------------------------------------','lin.ee','manj','L1V','LINE','LINE-','line.','line.me','LINE-https','link','mani','Add','.ME','and','Capacity','bit.ly','-https']
        if len(extracted_id) > 2 and extracted_id.lower() not in [b.lower() for b in blacklist]:
            return extracted_id
            
    return None

def convert_thai_date(text):
    if not isinstance(text, str):
        return pd.NaT 
        
    try:
        parts = text.split()
        if len(parts) >= 3:
            day = parts[0]
            month_th = parts[1]
            year_th = parts[2]
            
            month = thai_months.get(month_th, '01') 
            year_en = int(year_th) - 543
            
            standard_date_str = f"{year_en}-{month}-{day.zfill(2)}"
            return standard_date_str
            
        return pd.NaT
    except:
        return pd.NaT
